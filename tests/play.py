def cmd_coverage(args) -> int:
    """Runs the scripts with a coverage build, and the unit tests with `qb64rust test --coverage`
    when no script is named or --unit-tests is given, and reports the lines they reach (QB64Rust's
    tools/coverage/coverage.py). The reports go to tests/out/qb64/coverage/: report-won.txt and
    report-napoleon.txt, and the tables per SUB subs-won.txt and subs-napoleon.txt."""
    scripts = find_scripts(args.scripts)
    exes = build_all(["rust"], coverage=True)
    folder = OUT / "coverage"
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    counts = {s.name: folder / f"{s.name}.txt" for s in scripts}
    runs = parallel(args.jobs, [lambda s=s: coverage_run(s, exes, folder, counts[s.name]) for s in scripts])
    for run in runs:
        print(f"{'FAIL' if run.problem else 'ok  '}  {run.label}" + (f": {run.problem}" if run.problem else ""))
    have = [p for p in counts.values() if p.is_file()]
    if args.unit_tests or not args.scripts:
        unit = unit_test_counts(folder, args.jobs)
        if unit:
            added = reached_only_by(unit, have)
            print(f"  the unit tests reach {added} statements that no script reaches")
            have.append(unit)
    if not have:
        raise SetupError("no run wrote its counts")
    for program, source in PROGRAMS.items():
        own = [program_records(p, program, folder / "by-program" / f"{program}-{p.name}") for p in have]
        coverage_report(folder, program, source, [p for p in own if p])
    return 0


# The files of each program: a count file keeps only these for the program's report. QB64.BM is in
# both, so each report counts it as that program runs it.
PROGRAM_FILES = {
    "won": {"won.bas", "won.bi", "won1.bm", "won2.bm", "wonmenu.bm", "qb64.bm", "script.bm"},
    "napoleon": {"napoleon.bas", "nap10.bi", "nap1.bm", "nap1a.bm", "nap1c.bm", "qb64.bm", "napscript.bm"},
}


def coverage_run(script: Script, exes, folder: Path, counts: Path) -> Run:
    """A run of a coverage build. A coverage build writes its counts when the program ends, but
    not when it is killed, so a session (which run_script stops once its last state is written)
    gets one more prompt: no wait comes, and the screen tool ends the program after 20 seconds with
    exit code 124 and "no prompt in time", which counts as the run's right end only when it is that
    last prompt that timed out: every step before it ran. A session that went out of step ends the
    same way, at an earlier line."""
    keys, env, last = None, {"QB64RUST_COVERAGE": str(counts)}, 0
    if script.stop_after is not None:
        keys = folder / "keys" / f"{script.name}.keys"
        keys.parent.mkdir(parents=True, exist_ok=True)
        text = script.keys.read_text(encoding="ascii").rstrip("\n") + "\nprompt\n"
        keys.write_text(text, encoding="ascii")
        last = text.count("\n")
        script = Script(**{**script.__dict__, "stop_after": None})
        # The limit holds for every prompt of the run, and session 15's high-score music plays for
        # more than 3 seconds before its next wait.
        env["QB64_SCREEN_PROMPT_MS"] = "20000"
    run = run_script(script, "rust", exes, tag="coverage", keys=keys, extra_env=env)
    if keys and run.problem and expected_end(run.problem, last):
        run.problem = None
    if run.problem is None and not counts.is_file():
        run.problem = "no counts written"
    return run


def expected_end(problem: str, line: int) -> bool:
    """True when a run's problem is the screen tool's "no prompt in time" at the given line of its
    keys file, with exit code 124."""
    return (problem.startswith("exit code 124") and problem.endswith(f"line {line}: no prompt in time"))


def program_records(path: Path, program: str, out: Path) -> Path | None:
    """A copy of a count file with only the records of the program's files, or None when it has none."""
    keep_ids: set[str] = set()
    lines, found = [], False
    for line in path.read_text(encoding="latin-1").splitlines():
        parts = line.split("\t")
        if parts[0] == "file" and len(parts) >= 4:
            if Path(parts[3]).name.lower() in PROGRAM_FILES[program]:
                keep_ids.add(parts[1])
                lines.append(line)
                found = True
        elif len(parts) >= 4 and parts[0].isdigit():
            if parts[0] in keep_ids:
                lines.append(line)
        else:
            if line.startswith("coverage "):
                keep_ids = set()
            lines.append(line)
    if not found:
        return None
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="latin-1")
    return out


def coverage_report(folder: Path, program: str, source: str, have: list[Path]) -> None:
    """Writes the coverage report of one program from the count files, and its table per SUB."""
    print(f"{source}:")
    r = subprocess.run([sys.executable, "-I", str(COVERAGE_TOOL), "--program", str(REPO / source), *map(str, have)],
                       capture_output=True, text=True)
    report = folder / f"report-{program}.txt"
    report.write_text(r.stdout + r.stderr)
    if r.returncode != 0:
        print(r.stdout + r.stderr)
        raise SetupError(f"coverage.py failed (exit code {r.returncode})")
    total = [0, 0, 0, 0]
    for line in r.stdout.splitlines():
        name, sep, rest = line.partition(": ")
        if not sep or line.startswith(" ") or "lines with a statement" not in rest:
            continue
        numbers = [int(w) for w in rest.replace(",", " ").replace(":", " ").split() if w.isdigit()]
        if len(numbers) == 4 and numbers[0]:
            total = [t + n for t, n in zip(total, numbers)]
            print(f"  {name:12} {100 * (numbers[1] + numbers[2]) / numbers[0]:5.1f}%  {rest}")
    if total[0]:
        print(f"  {'all':12} {100 * (total[1] + total[2]) / total[0]:5.1f}%  {total[0]} lines with a statement: "
              f"{total[1]} run, {total[2]} partly run, {total[3]} not run")
    subs = folder / f"subs-{program}.txt"
    subs.write_text(sub_table(have, source.lower(), files_of(r.stdout)))
    print(f"  report: {rel(report)}; per SUB: {rel(subs)}")


def files_of(report: str) -> set[str]:
    """The source files a coverage report covers, in lower case."""
    return {line.partition(": ")[0].strip().lower() for line in report.splitlines()
            if not line.startswith(" ") and "lines with a statement" in line}


def unit_test_counts(folder: Path, jobs: int) -> Path | None:
    """Runs the unit tests (`qb64rust test tests --coverage`) and writes their counts to
    folder/unit-tests.txt, with the game's files named as the scripts' records name them."""
    raw, log = folder / "unit-tests-raw.txt", folder / "unit-tests-log.txt"
    print("running the unit tests with --coverage ...", flush=True)
    env = dict(os.environ, QB64RUST_COVERAGE=str(raw))
    cmd = [str(COMPILERS["rust"]), "test", "tests", "--coverage", "--jobs", str(jobs)]
    with open(log, "wb") as out:
        rc = subprocess.run(cmd, stdout=out, stderr=subprocess.STDOUT, cwd=REPO, env=env).returncode
    print(f"{'FAIL' if rc else 'ok  '}  unit tests" + (f": exit code {rc}; see {rel(log)}" if rc else ""))
    if not raw.is_file():
        return None
    rebased = folder / "unit-tests.txt"
    rebased.write_text(rebase_records(raw.read_text(encoding="latin-1")), encoding="latin-1")
    return rebased


def rebase_records(text: str) -> str:
    """Coverage records of the unit tests, made from tests/, as records of the game's folder. A file
    named `../<name>` becomes `<name>`; the test entry point, the test library and the test file are
    left out with their counts, as they are not files of the game."""
    out: list[str] = []
    keep: set[str] = set()
    for line in text.splitlines():
        parts = line.split("\t")
        if parts[0] == "file" and len(parts) == 4:
            name = parts[3]
            if name.startswith("../") and "/" not in name[3:]:
                keep.add(parts[1])
                out.append("\t".join([*parts[:3], name[3:]]))
        elif len(parts) >= 4 and parts[0].isdigit():
            if parts[0] in keep:
                out.append(line)
        else:
            if line.startswith("coverage "):
                keep = set()
            out.append(line)
    return "\n".join(out) + "\n"


def statement_counts(count_files: list[Path]) -> dict[tuple[str, int, int], int]:
    """Each statement's count, merged over the records of the files: by (file name in lower case,
    line, column)."""
    counts: dict[tuple[str, int, int], int] = {}
    for path in count_files:
        names: dict[str, str] = {}
        for line in path.read_text(encoding="latin-1").splitlines():
            parts = line.split("\t")
            if parts[0] == "file" and len(parts) >= 4:
                names[parts[1]] = parts[3]
            elif len(parts) >= 4 and parts[0] in names and parts[1].isdigit():
                key = (names[parts[0]].lower(), int(parts[1]), int(parts[2]))
                counts[key] = counts.get(key, 0) + int(parts[3])
    return counts


def reached_only_by(unit: Path, scripts: list[Path]) -> int:
    """How many statements the counts of `unit` ran that no record of `scripts` ran."""
    by_scripts = statement_counts(scripts)
    return sum(1 for key, n in statement_counts([unit]).items() if n and not by_scripts.get(key))


def sub_table(count_files: list[Path], main: str, files: set[str] | None = None) -> str:
    """The statements each SUB and FUNCTION has and runs, from coverage records, the least covered
    first. main is the file of the main module, in lower case; files, when given, the files of the
    program, so that the table of one program leaves out the other's."""
    counts = {k: v for k, v in statement_counts(count_files).items() if files is None or k[0] in files}
    starts: dict[str, list[tuple[int, str]]] = {}
    for name in {k[0] for k in counts}:
        source = next((p for p in REPO.iterdir() if p.name.lower() == name), None)
        found: list[tuple[int, str]] = []
        if source:
            for n, text in enumerate(source.read_text(encoding="latin-1").splitlines(), 1):
                words = text.split()
                if len(words) >= 2 and words[0].upper() in ("SUB", "FUNCTION"):
                    found.append((n, words[1].split("(")[0]))
        starts[name] = found
    table: dict[tuple[str, str], list[int]] = {}
    for (name, line, _), count in counts.items():
        proc = "(main module)" if name == main else "(outside procedures)"
        for n, sub in starts[name]:
            if n <= line:
                proc = sub
        entry = table.setdefault((name, proc), [0, 0])
        entry[0] += 1
        entry[1] += count > 0
    rows = sorted(table.items(), key=lambda kv: (-(kv[1][0] - kv[1][1]), kv[0]))
    out = [f"{'file':12} {'procedure':22} {'statements':>10} {'run':>6} {'not run':>8} {'run %':>6}"]
    for (name, proc), (total, run) in rows:
        out.append(f"{name:12} {proc:22} {total:10} {run:6} {total - run:8} {100 * run / total:6.1f}")
    return "\n".join(out) + "\n"


