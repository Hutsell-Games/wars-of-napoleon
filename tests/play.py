"""Plays the port's QB64 builds from keys files, and compares their screens and files with the
port's own references and with the DOSBox-X recordings (tests/README.md; steps 7 and 8 of
docs/port-study.md).

Usage (from the repo's folder):
    python -I tests/play.py check    [--compiler rust|pe] [script ...]  against the references
    python -I tests/play.py compare  [script ...]   the QB64Rust and QB64pe builds against each other
    python -I tests/play.py record   [script ...]   both builds, twice each; writes <keys>.screen
    python -I tests/play.py bridge   [--compiler rust|pe|both] [session ...]   against the DOS recordings
    python -I tests/play.py tactical [--compiler rust|pe|both] [battle ...]    against the DOS recordings
    python -I tests/play.py coverage [--unit-tests] [script ...]   the lines the scripts and unit tests reach
    python -I tests/play.py explore  [--compiler rust|pe] <keys file>   a PNG of every state; stops at the next wait
--jobs N, before or after the command, sets how many runs go at once (default 4).

A script is a keys file of QB64Rust's screen tool (its tools/screen/README.md), of one of four kinds:

- a session, tests/sessions/<name>.keys: one of the 15 sessions recorded in DOSBox-X, written
  by tools/play/sessions.py. It ends at the wait of its last shot, and the run is stopped once
  the state of that shot is written;
- session 9 with its battle, 09-1805-tactical-battle (D4 of the plan): session 9's keys file
  again, but the strategic game starts the port's tactical game, which plays
  tests/battles/b1-innsbruck-retreat.keys (BATTLED_SESSIONS below);
- a battle, tests/battles/<name>.keys: the tactical game alone, with <name>.battle as its
  BATTLE.$$$. It runs until the game exits;
- a game, tests/games/<name>.keys: the strategic game from its start to its end (generated by
  tests/make_scripts.py, or written by hand). It runs until the game exits.

A script is named by its file's stem or a pattern such as "1*" or "b*"; none means all of them.

A game's "#!" lines set up its run (other "#" lines are comments):
    #! seed <n>               the random seed (WON_SEED; default 1)
    #! timeout <seconds>      the longest the run may take (default 900)
    #! battle <keys file>     the keys of the next battle the strategic game starts, by
                              SHELL "napoleon.exe" (scriptbattle, SCRIPT.BM); a path from the
                              repo's folder. Without one, no battle starts: WON_OUTCOME names a
                              file that is not there, which scriptbattle copies as nothing
    #! save <file> <as>       a file of tests/data copied into the run's folder under the name
                              <as> before the run, such as a saved game

A reference (<keys>.screen, written by record) holds one line per entry of the run: each state
of the strategic game (or of the tactical game, for a battle) as its digest, then each state
the tactical game wrote during a battle the strategic game started, as "battle<n> digest ...",
then "file <name> <hash>" for each file the run wrote or changed. The digest is the FNV-1a 64
hash of the state that QB64Rust's screen tool gives (its tools/screen/README.md, "digest").

bridge and tactical hold the runs to the DOSBox-X recordings, through tests/dosshot.py and the
known differences of tests/known-differences.txt. A difference that the list explains counts as
equal; a known difference that a run no longer meets is reported, so that the list stays true.

How a run is kept safe on the host (CLAUDE.md of QB64Rust, working rule 6): the window goes on
a desktop of its own that is never shown (press_any_key.py --hidden-desktop). The run's folder
holds no DOS program, so the game's SHELLs of ARCH2.EXE, VIC.EXE and RRS.EXE do not run; under
a script the copy of the history file is done in BASIC (SCRIPT.BM). A battle that a script
starts runs napoleon.exe directly, which libqb starts with no console, on the same hidden
desktop (docs/devnotes.md, "Step 3", item 3).

Exit code: 0 when every run passed, 1 when one failed, 2 when a build or the set-up failed.
"""
