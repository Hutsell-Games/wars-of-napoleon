def rel(path) -> str:
    try:
        return Path(path).resolve().relative_to(REPO).as_posix()
    except ValueError:
        return str(path)


class Tee:
    """Writes to several streams at once."""

    def __init__(self, *streams):
        self.streams = streams

    def write(self, text: str) -> int:
        for s in self.streams:
            s.write(text)
            s.flush()
        return len(text)

    def flush(self) -> None:
        for s in self.streams:
            s.flush()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("command", choices=["check", "compare", "record", "bridge", "tactical", "coverage", "explore"])
    ap.add_argument("scripts", nargs="*", help="scripts (for explore: one keys file); none means all")
    ap.add_argument("--compiler", choices=["rust", "pe", "both"], default="rust")
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--unit-tests", action="store_true", help="coverage: run the unit tests when scripts are named")
    ap.add_argument("--wait-ms", type=int, default=5000, help="explore: how long the last prompt waits")
    args = ap.parse_intermixed_args(argv)
    if os.name != "nt":
        raise SystemExit("play.py runs on Windows only for now (TODO.md, Linux)")
    if args.compiler == "both" and args.command not in ("bridge", "tactical"):
        raise SystemExit("--compiler both is for bridge and tactical")
    OUT.mkdir(parents=True, exist_ok=True)
    log = open(OUT / f"last-{args.command}.txt", "w", encoding="utf-8")
    sys.stdout = Tee(sys.stdout, log)
    try:
        if args.command == "explore":
            if len(args.scripts) != 1:
                raise SetupError("explore takes one keys file")
            args.keys = args.scripts[0]
            return cmd_explore(args)
        if args.command == "bridge":
            return cmd_hold(args, ("session",))
        if args.command == "tactical":
            return cmd_hold(args, ("battle",))
        return {"check": cmd_check, "compare": cmd_compare, "record": cmd_record,
                "coverage": cmd_coverage}[args.command](args)
    except SetupError as e:
        print(f"play.py: {e}")
        return 2
    finally:
        sys.stdout = sys.stdout.streams[0]
        log.close()


if __name__ == "__main__":
    sys.exit(main())
