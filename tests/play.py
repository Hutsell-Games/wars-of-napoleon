# ------------------------------------------------------------------------------- building


def build(compiler: str, source: str = "WON.BAS", coverage: bool = False) -> Path:
    """The program built by the compiler with the screen hook, unless the same sources are
    built: won.exe from WON.BAS, napoleon.exe from NAPOLEON.BAS. With coverage (QB64Rust only)
    the build counts each statement it runs."""
    exe = COMPILERS[compiler]
    if not exe.is_file():
        raise SetupError(f"compiler not found: {exe}")
    stem = Path(source).stem.lower()
    folder = OUT / "build" / (compiler + ("-coverage" if coverage else "")) / stem
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / (stem + ".exe")
    h = hashlib.sha256()
    for p in sorted(REPO.iterdir()):
        if p.is_file() and p.suffix.lower() in SOURCES:
            h.update(p.name.encode() + b"\0" + p.read_bytes() + b"\0")
    h.update(source.encode() + b"\0" + (REPO / source).read_bytes() + b"\0")
    st = exe.stat()
    h.update(f"{exe}\0{st.st_size}\0{st.st_mtime_ns}\0{coverage}\0".encode() + SCREEN_HOOK.read_bytes())
    stamp, stamp_file = h.hexdigest(), folder / "stamp.txt"
    if target.is_file() and stamp_file.is_file() and stamp_file.read_text() == stamp:
        return target
    target.unlink(missing_ok=True)
    print(f"building {source} with {compiler}{' --coverage' if coverage else ''} ...", flush=True)
    log = folder / "build-log.txt"
    cmd = [str(exe), "-x", *(["--coverage"] if coverage else []), str(REPO / source), "-o", str(target),
           f"-f:ExtraLinkerFlags={SCREEN_HOOK.resolve().as_posix()}"]
    with open(log, "wb") as out:
        rc = subprocess.run(cmd, stdout=out, stderr=subprocess.STDOUT, cwd=REPO).returncode
    if rc != 0 or not target.is_file():
        raise SetupError(f"the {compiler} build of {source} failed (exit code {rc}); see {rel(log)}")
    stamp_file.write_text(stamp)
    return target


def build_all(compilers: list[str], coverage: bool = False) -> dict[tuple[str, str], Path]:
    """Both programs with each compiler: {(compiler, program): exe}. The compilers at once."""
    def one(c):
        return {(c, p): build(c, s, coverage) for p, s in PROGRAMS.items()}

    found = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=len(compilers)) as pool:
        for part in pool.map(one, compilers):
            found.update(part)
    return found


# -------------------------------------------------------------------------------- scripts


@dataclass
class Script:
    name: str
    kind: str  # session, battle or game
    keys: Path
    program: str = "won"
    seed: str = "1"
    timeout: int = TIMEOUT
    outcome: str | None = None  # WON_OUTCOME; None: a battle starts the tactical game
    battle_file: Path | None = None  # the tactical game's BATTLE.$$$ (kind battle)
    battles: list[Path] = field(default_factory=list)  # the keys of each battle the strategic game starts
    saves: list[tuple[Path, str]] = field(default_factory=list)
    stop_after: int | None = None  # states; the run is stopped once they are written
    shots: list[str] = field(default_factory=list)  # the shot of each state step
    reference: Path | None = None

    def __post_init__(self):
        if self.reference is None:
            self.reference = self.keys.with_suffix(".screen")


def shots_of(text: str) -> list[str]:
    """The shot of each "state" step, in order: the comment "# shot NAME" before it."""
    shots, pending = [], None
    for line in text.splitlines():
        m = re.match(r"# shot (\S+?)(:.*)?$", line)
        if m:
            pending = m.group(1)
        elif line.split("#", 1)[0].strip() == "state":
            shots.append(pending)
            pending = None
    return shots


def session_script(keys: Path, name: str | None = None, battle: Path | None = None) -> Script:
    text = keys.read_text(encoding="ascii")
    seed = re.search(r"^# seed (\S+) \(WON_SEED\)", text, re.M).group(1)
    shots = shots_of(text)
    has_battle = "WON_OUTCOME" in text.split("\n\n", 1)[0]
    if battle is not None:
        outcome, battles = None, [battle]
    elif has_battle:
        outcome, battles = str(RECORDED / keys.stem / "files" / "OUTCOME.&&&"), []
    else:
        outcome, battles = NO_OUTCOME, []
    s = Script(name or keys.stem, "session", keys, seed=seed, outcome=outcome, battles=battles,
               stop_after=len(shots), shots=shots)
    if name:
        s.reference = keys.with_name(name + ".screen")
    return s


def battle_script(keys: Path) -> Script:
    text = keys.read_text(encoding="ascii")
    seed = re.search(r"^# seed (\S+) \(NAP_SEED\)", text, re.M)
    if not seed:
        raise SetupError(f"{rel(keys)}: no '# seed N (NAP_SEED)' line")
    return Script(keys.stem, "battle", keys, program="napoleon", seed=seed.group(1),
                  battle_file=keys.with_suffix(".battle"), shots=shots_of(text))


def game_script(keys: Path) -> Script:
    """A game's keys file, with its "#!" lines."""
    s = Script(keys.stem, "game", keys, outcome=NO_OUTCOME)
    text = keys.read_text(encoding="ascii")
    for n, line in enumerate(text.splitlines(), 1):
        if not line.startswith("#!"):
            continue
        words = line[2:].split()
        where = f"{rel(keys)} line {n}"
        if words[:1] == ["seed"] and len(words) == 2:
            s.seed = words[1]
        elif words[:1] == ["timeout"] and len(words) == 2 and words[1].isdigit():
            s.timeout = int(words[1])
        elif words[:1] == ["battle"] and len(words) == 2:
            path = REPO / words[1]
            if not path.is_file():
                raise SetupError(f"{where}: no keys file {words[1]}")
            s.battles.append(path)
            s.outcome = None
        elif words[:1] == ["save"] and len(words) == 3:
            path = TEST_DATA / words[1]
            if not path.is_file():
                raise SetupError(f"{where}: no file {rel(path)}")
            s.saves.append((path, words[2]))
        else:
            raise SetupError(f"{where}: not a set-up line: {line}")
    s.shots = shots_of(text)
    return s


def all_scripts() -> list[Script]:
    found = [session_script(k) for k in sorted(SESSIONS.glob("*.keys"))]
    for name, (session, battle) in BATTLED_SESSIONS.items():
        found.append(session_script(SESSIONS / f"{session}.keys", name, battle))
    found += [battle_script(k) for k in sorted(BATTLES.glob("*.keys"))]
    found += [game_script(k) for k in sorted(GAMES.glob("*.keys"))]
    return found


def find_scripts(names: list[str], kinds: tuple[str, ...] = ("session", "battle", "game")) -> list[Script]:
    """The scripts named (a stem, a pattern, or a keys file's path), or all of the kinds."""
    every = [s for s in all_scripts() if s.kind in kinds]
    if not names:
        return every
    picked: list[Script] = []
    for n in names:
        stem = Path(n).stem if n.endswith(".keys") else n
        hits = [s for s in every if fnmatch.fnmatchcase(s.name, stem)]
        if not hits:
            raise SetupError(f"no script {n!r} (kinds: {', '.join(kinds)})")
        picked += [s for s in hits if s not in picked]
    return picked


# ---------------------------------------------------------------------------------- entries


def entries(data: bytes) -> list[bytes]:
    """The entries of a state file in order: each state from `screen-state 1` to `end` (with its
    line ends), each `digest` line, and a last `stopped` line if a `prompt` stopped the run."""
    found: list[bytes] = []
    current: list[bytes] | None = None
    for line in data.splitlines(keepends=True):
        if current is not None:
            current.append(line)
            if line.rstrip(b"\r\n") == b"end":
                found.append(b"".join(current))
                current = None
        elif line.startswith(b"screen-state "):
            current = [line]
        elif line.strip():
            found.append(line.rstrip(b"\r\n"))
    if current is not None:
        found.append(b"".join(current))  # a state cut short
    return found


def fnv1a64(data: bytes) -> int:
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def as_digest(entry: bytes) -> bytes:
    """A full state as the `digest` line the same screen gives; any other entry as it is."""
    if entry.startswith(b"screen-state "):
        return b"digest %016X" % fnv1a64(entry)
    return entry


def first_difference(a: list[bytes], b: list[bytes]) -> int | None:
    """The index of the first entry that differs, or None when the two lists are the same."""
    for i in range(max(len(a), len(b))):
        if i >= len(a) or i >= len(b) or a[i] != b[i]:
            return i
    return None


def file_line(path: Path) -> bytes:
    """A file the run wrote, as "file <name> <hash>": the name in upper case, as DOS gives it,
    and the start of the SHA-256 of its bytes."""
    return f"file {path.name.upper()} {hashlib.sha256(path.read_bytes()).hexdigest()[:16].upper()}".encode()


# ------------------------------------------------------------------------------------ runs


@dataclass
class Run:
    script: Script
    compiler: str
    tag: str
    folder: Path
    problem: str | None
    seconds: float
    states: list[bytes]  # the strategic game's entries (the tactical game's, for a battle)
    battle_states: list[list[bytes]]  # the entries of each battle the strategic game started
    files: list[Path]  # the files the run wrote or changed

    @property
    def label(self) -> str:
        return f"{self.script.name} [{self.compiler}{' ' + self.tag if self.tag else ''}]"

    def reference_entries(self) -> list[bytes]:
        """The entries a reference keeps: states as digests, then the battles' states, then the files."""
        out = [as_digest(e) for e in self.states]
        for n, battle in enumerate(self.battle_states, 1):
            out += [b"battle%d " % n + as_digest(e) for e in battle]
        out += [file_line(p) for p in self.files]
        return out


def kill_tree(proc: subprocess.Popen) -> None:
    subprocess.run(["taskkill", "/F", "/T", "/PID", str(proc.pid)], capture_output=True)
    proc.wait()


def count_states(path: Path) -> int:
    try:
        return path.read_bytes().count(b"\nend\n")
    except OSError:
        return 0


def run_script(script: Script, compiler: str, exes: dict[tuple[str, str], Path], tag: str = "",
               keys: Path | None = None, extra_env: dict[str, str] | None = None) -> Run:
    """One run of the script in a fresh folder of the game's files."""
    folder = OUT / "run" / f"{script.name}-{compiler}{'-' + tag if tag else ''}"
    shutil.rmtree(folder, ignore_errors=True)
    game = folder / "game"
    game.mkdir(parents=True)
    replaced = ("BATTLE.$$$", "OUTCOME.&&&") if script.program == "napoleon" else ()
    for p in harness.game_files(replaced):
        if p.suffix.lower() != ".exe":
            shutil.copy2(p, game / p.name)
    if script.battle_file:
        shutil.copy2(script.battle_file, game / "BATTLE.$$$")
    for path, name in script.saves:
        shutil.copy2(path, game / name)
    before = {p.name: harness.sha(p) for p in game.iterdir()}
    exe = game / f"{script.program}.exe"
    shutil.copy2(exes[compiler, script.program], exe)
    if script.battles:
        shutil.copy2(exes[compiler, "napoleon"], game / "napoleon.exe")
    # The keys file, and beside it the keys of each battle, as scriptbattle looks for them.
    run_keys = folder / "keys.keys"
    shutil.copy2(keys or script.keys, run_keys)
    for n, battle in enumerate(script.battles, 1):
        shutil.copy2(battle, folder / f"keys.keys.battle{n}")
    state = folder / "screen.txt"
    env = dict(os.environ)
    for name in RUN_VARIABLES:
        env.pop(name, None)
    env.update({"QB64PE_NOPROMPT": "y", "QB64_SCREEN_KEYS": str(run_keys), "QB64_SCREEN_STATE": str(state)})
    if script.program == "napoleon":
        env["NAP_SEED"] = script.seed
    else:
        env["WON_SEED"] = script.seed
        if script.outcome is not None:
            env["WON_OUTCOME"] = script.outcome
    env.update(extra_env or {})
    cmd = [sys.executable, "-I", str(PRESS_ANY_KEY), "--hidden-desktop", str(exe)]
    problem, start = None, time.monotonic()
    with open(folder / "log.txt", "wb") as log:
        proc = subprocess.Popen(cmd, cwd=game, env=env, stdout=log, stderr=subprocess.STDOUT,
                                stdin=subprocess.DEVNULL, creationflags=subprocess.CREATE_NO_WINDOW)
        while True:
            if script.stop_after is not None and count_states(state) >= script.stop_after:
                time.sleep(0.5)  # let the files of that moment be closed
                kill_tree(proc)
                break
            if proc.poll() is not None:
                break
            if time.monotonic() - start > script.timeout:
                kill_tree(proc)
                problem = f"stopped after {script.timeout} s"
                break
            time.sleep(0.2)
    data = state.read_bytes() if state.is_file() else b""
    found = entries(data)
    if problem is None:
        if found and found[-1].startswith(b"stopped "):
            problem = f"exit code {proc.returncode}: {found[-1].decode(errors='replace')}"
        elif script.stop_after is not None and len(found) < script.stop_after:
            problem = f"ended with exit code {proc.returncode} after {len(found)} of {script.stop_after} states"
        elif script.stop_after is None and proc.returncode != 0:
            problem = f"exit code {proc.returncode}"
        elif not found:
            problem = f"exit code {proc.returncode} and no state written"
    battle_states = []
    for n in range(1, len(script.battles) + 1):
        path = Path(f"{state}.battle{n}")
        battle = entries(path.read_bytes()) if path.is_file() else []
        if problem is None and (not battle or battle[-1].startswith(b"stopped ")):
            problem = f"battle {n}: " + (battle[-1].decode(errors="replace") if battle else "no state written")
        battle_states.append(battle)
    files = []
    for p in sorted(game.iterdir(), key=lambda p: p.name.upper()):
        if p.suffix.lower() != ".exe" and before.get(p.name) != harness.sha(p):
            files.append(p)
    return Run(script, compiler, tag, folder, problem, time.monotonic() - start, found, battle_states, files)


def parallel(jobs: int, work: list) -> list:
    with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as pool:
        return list(pool.map(lambda f: f(), work))


def describe(run: Run, index: int) -> str:
    """Where entry index of a reference comes from."""
    n_states = len(run.states)
    if index < n_states:
        shot = run.script.shots[index] if index < len(run.script.shots) and run.script.shots[index] else None
        return f"state {index + 1}" + (f" (shot {shot})" if shot else "")
    index -= n_states
    for n, battle in enumerate(run.battle_states, 1):
        if index < len(battle):
            return f"battle {n}, state {index + 1}"
        index -= len(battle)
    return "the files"


# ---------------------------------------------------------------------------- the references


def cmd_record(args) -> int:
    scripts = find_scripts(args.scripts)
    exes = build_all(["rust", "pe"])
    work = [lambda s=s, c=c, t=t: run_script(s, c, exes, tag=t)
            for s in scripts for c in ("rust", "pe") for t in ("1", "2")]
    runs = parallel(args.jobs, work)
    failed = 0
    for i, script in enumerate(scripts):
        group = runs[4 * i:4 * i + 4]
        problems = [f"{r.label}: {r.problem}" for r in group if r.problem]
        first = group[0].reference_entries()
        differ = [r.label for r in group[1:] if r.reference_entries() != first]
        if problems or differ:
            failed += 1
            print(f"FAIL  {script.name}: not recorded")
            for p in problems:
                print(f"    {p}")
            if differ:
                print(f"    differs from {group[0].label}: {', '.join(differ)}")
            continue
        script.reference.write_bytes(b"\n".join(first) + b"\n")
        print(f"ok    {script.name}: {len(first)} entries, the same in 4 runs; wrote {rel(script.reference)}")
    print(f"{len(scripts) - failed} recorded, {failed} failed")
    return 1 if failed else 0


def cmd_check(args) -> int:
    scripts = find_scripts(args.scripts)
    missing = [s.name for s in scripts if not s.reference.is_file()]
    if missing:
        raise SetupError(f"not recorded: {', '.join(missing)} (python -I tests/play.py record <name>)")
    exes = build_all([args.compiler])
    runs = parallel(args.jobs, [lambda s=s: run_script(s, args.compiler, exes) for s in scripts])
    failed = 0
    for run in runs:
        want = run.script.reference.read_bytes().splitlines()
        got = run.reference_entries()
        index = first_difference(got, want)
        if run.problem is None and index is None:
            print(f"ok    {run.label}: {len(got)} entries, {run.seconds:.0f} s")
            continue
        failed += 1
        if index is None:
            print(f"FAIL  {run.label}: {run.problem}")
            continue
        print(f"FAIL  {run.label}: differs at entry {index + 1}, {describe(run, index)}"
              + (f"; {run.problem}" if run.problem else ""))
        print(f"    reference: {want[index].decode(errors='replace') if index < len(want) else 'nothing'}")
        print(f"    now:       {got[index].decode(errors='replace') if index < len(got) else 'nothing'}")
        print(f"    the run's folder: {rel(run.folder)}")
    print(f"{len(runs) - failed} passed, {failed} failed")
    return 1 if failed else 0


def cmd_compare(args) -> int:
    scripts = find_scripts(args.scripts)
    exes = build_all(["rust", "pe"])
    runs = parallel(args.jobs, [lambda s=s, c=c: run_script(s, c, exes) for s in scripts for c in ("rust", "pe")])
    failed = 0
    for rust, pe in zip(runs[0::2], runs[1::2]):
        name = rust.script.name
        problems = [f"{r.compiler}: {r.problem}" for r in (rust, pe) if r.problem]
        a, b = rust.reference_entries(), pe.reference_entries()
        index = first_difference(a, b)
        if index is None and not problems:
            note = ""
            if rust.script.reference.is_file():
                same = first_difference(a, rust.script.reference.read_bytes().splitlines()) is None
                note = "; same as the reference" if same else "; NOT the reference"
                failed += not same
            print(f"{'ok  ' if 'NOT' not in note else 'FAIL'}  {name}: both builds give the same {len(a)} entries{note}")
            continue
        failed += 1
        if index is None:
            print(f"FAIL  {name}: {'; '.join(problems)}")
            continue
        print(f"FAIL  {name}: the builds differ at entry {index + 1}, {describe(rust, index)}"
              + (f"; {'; '.join(problems)}" if problems else ""))
        print(f"    qb64rust: {a[index].decode(errors='replace') if index < len(a) else 'nothing'}")
        print(f"    qb64pe:   {b[index].decode(errors='replace') if index < len(b) else 'nothing'}")
    print(f"{len(scripts) - failed} passed, {failed} failed")
    return 1 if failed else 0


