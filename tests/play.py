def cmd_explore(args) -> int:
    """One run of a keys file, then a wait that no prompt answers, so the run stops at the wait
    after the file's last step. A PNG of every state goes to tests/out/qb64/explore/."""
    path = Path(args.keys)
    if path.parent.resolve() == BATTLES.resolve():
        script = battle_script(path)
    elif path.parent.resolve() == SESSIONS.resolve():
        script = session_script(path)
        script.stop_after = None
    else:
        script = game_script(path)
    exes = build_all([args.compiler])
    folder = OUT / "explore"
    folder.mkdir(parents=True, exist_ok=True)
    keys = folder / f"{script.name}.keys"
    text = path.read_text(encoding="ascii")
    steps = [line.split("#", 1)[0].split() for line in text.splitlines()]
    steps = [s for s in steps if s]
    last = steps[-1] if steps else []
    if last[:1] == ["repeat"] and len(last) == 2 and not last[1].isdigit():
        added = ""
    elif last[:1] and last[0] in {"text", "key"}:
        added = "prompt\nstate\nprompt\n"
    else:
        added = "prompt\n"
    keys.write_text(text.rstrip("\n") + "\n" + ("# added by explore\n" + added if added else ""))
    run = run_script(script, args.compiler, exes, tag="explore", keys=keys,
                     extra_env={"QB64_SCREEN_PROMPT_MS": str(args.wait_ms), "QB64_SCREEN_DIGEST_AS_STATE": "1"})
    for old in folder.glob(f"{script.name}-*.png"):
        old.unlink()
    tool = QB64RUST / "tools" / "screen" / "state_to_png.py"
    r = subprocess.run([sys.executable, "-I", str(tool), "--all", str(run.folder / "screen.txt"), "-o",
                        str(folder / f"{script.name}.png")], capture_output=True, text=True)
    last_entry = run.states[-1].decode(errors="replace").splitlines()[0] if run.states else "none"
    print(f"{len(run.states)} entries; last: {last_entry}" + (f"; {run.problem}" if run.problem else ""))
    for line in r.stdout.splitlines():
        if line.startswith("written: "):
            print(f"  {rel(Path(line[9:]))}")
    return 0


