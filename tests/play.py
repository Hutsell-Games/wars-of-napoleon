def load_fonts(compiler: str) -> dict[str, dict[int, bytes]]:
    """The glyphs dosshot needs: QB64's 8 x 14 (tests/font9.bas) and 8 x 16 (tests/font12.bas),
    each built by the compiler and run once under the screen tool, and DOS's 8 x 14 from
    tests/recorded/dosbox-x-font-8x14.bin, which tools/play/play.py font writes."""
    dos_file = RECORDED / "dosbox-x-font-8x14.bin"
    if not dos_file.is_file():
        raise SetupError(f"no DOS font: run tools/play/play.py font to write {rel(dos_file)}")
    data = dos_file.read_bytes()
    fonts = {"dos-14": {c: data[14 * c:14 * c + 14] for c in range(256)}}
    for name, source, height, skip in (
            ("qb64-14", "tests/font9.bas", 14, (7, 9, 10, 11, 12, 13, 28, 29, 30, 31)),
            ("qb64-16", "tests/font12.bas", 16, ())):
        exe = build(compiler, source)
        folder = OUT / "run" / f"{Path(source).stem}-{compiler}"
        shutil.rmtree(folder, ignore_errors=True)
        folder.mkdir(parents=True)
        state = folder / "screen.txt"
        env = dict(os.environ, QB64PE_NOPROMPT="y", QB64_SCREEN_STATE=str(state))
        env.pop("QB64_SCREEN_KEYS", None)
        subprocess.run([sys.executable, "-I", str(PRESS_ANY_KEY), "--hidden-desktop", str(exe)], cwd=folder,
                       env=env, stdin=subprocess.DEVNULL, capture_output=True, timeout=120, check=False,
                       creationflags=subprocess.CREATE_NO_WINDOW)
        states = [e for e in entries(state.read_bytes() if state.is_file() else b"") if e.startswith(b"screen-state")]
        if not states:
            raise SetupError(f"{source} wrote no state with {compiler}")
        page = dosshot.read_page(states[-1].decode("latin-1"))
        glyphs = {}
        for c in range(256):
            if c in skip:
                continue  # font9.bas does not print them
            x0, y0 = (c % 32) * 8, (c // 32) * height
            glyphs[c] = bytes(sum(128 >> i for i in range(8) if page.rows[y0 + r][x0 + i] != 0)
                              for r in range(height))
        fonts[name] = glyphs
    return fonts


@dataclass
class Held:
    """A run held to its DOS recording."""
    bad: int
    summary: str
    lines: list[str]
    used: set[int]


def hold_to_recording(run: Run, recording: str, known: list[dosshot.Known], fonts, masks,
                      numbered: bool) -> Held:
    """The run's shots against the recorded PNGs, and the files the recording's run wrote.
    numbered: the battles' shots are saved as NN-name.png."""
    lines, bad, used = [], 0, set()
    script = run.script
    states = [e for e in run.states if e.startswith(b"screen-state")]
    shots = script.shots
    equal = known_count = 0
    for i, shot in enumerate(shots):
        png = RECORDED / recording / "shots" / (f"{i + 1:02d}-{shot}.png" if numbered else f"{shot}.png")
        if i >= len(states):
            lines.append(f"  {shot}: no state")
            bad += 1
            continue
        if not png.is_file():
            lines.append(f"  {shot}: no recorded shot {rel(png)}")
            bad += 1
            continue
        got = dosshot.compare_shot(states[i].decode("latin-1"), png, script.name, shot, shots, known, fonts,
                                   run.folder / "diff" / f"{shot}.png", masks)
        used |= got.used
        if got.problem or not got.equal:
            lines.append(f"  {shot}: {got.problem or got.summary}")
            bad += 1
        elif got.summary == "known":
            known_count += 1
        else:
            equal += 1
    manifest_file = RECORDED / recording / "manifest.txt"
    manifest = harness.read_manifest(manifest_file) if manifest_file.is_file() else {}
    if not manifest:
        lines.append(f"  no recording: {rel(manifest_file)} is missing")
        bad += 1
    file_rules = [k for k in known if k.kind == "file" and fnmatch.fnmatchcase(script.name, k.run)]
    written = {p.name.upper(): p for p in run.files}
    for key, digest in sorted(manifest.items()):
        if not key.startswith("files/"):
            continue
        name = key[6:].upper()
        mine = written.pop(name, None)
        if script.kind == "session" and script.outcome and name == "OUTCOME.&&&":
            continue  # given by WON_OUTCOME, not written by the strategic game
        rule = next((k for k in file_rules if k.args[0].upper() == name), None)
        if mine is not None and harness.sha(mine) == digest:
            continue
        dos = RECORDED / recording / "files" / key[6:]
        if (mine is not None and name == "OUTCOME.&&&" and dos.is_file()
                and same_outcome(mine.read_text(encoding="ascii"), dos.read_text(encoding="ascii"))):
            continue
        if rule:
            used.add(rule.line)
            continue
        lines.append(f"  file {key[6:]}: {'not written' if mine is None else 'differs'}")
        bad += 1
    # A file the run wrote that DOS did not: an error, unless the list names it.
    for name in sorted(written):
        rule = next((k for k in file_rules if k.args[0].upper() == name), None)
        if rule:
            used.add(rule.line)
            continue
        lines.append(f"  file {name}: written, and not by DOS")
        bad += 1
    summary = f"{equal} of {len(shots)} shots equal"
    if known_count:
        summary += f", {known_count} equal but for known differences"
    return Held(bad, summary, lines, used)


def same_outcome(mine: str, dos: str) -> bool:
    """True when two OUTCOME.&&& texts give the same values. PDS 7.1's WRITE # gives a DOUBLE
    15 digits, QB64's 16 (QB64Rust's DIVERGENCES-QB45.md, Q-021): ".57999998703599" against
    ".5799999870359898". A field counts as equal when its text is, or when QB64's number
    rounded to 15 digits is DOS's."""
    a, b = mine.strip().split(","), dos.strip().split(",")
    if len(a) != len(b):
        return False
    for x, y in zip(a, b):
        if x == y:
            continue
        try:
            # BASIC writes a DOUBLE's exponent with D: 7.99999982118607D-02.
            mine_value, dos_value = float(x.replace("D", "E")), float(y.replace("D", "E"))
            if float(f"{mine_value:.15g}") != dos_value:
                return False
        except ValueError:
            return False
    return True


def cmd_hold(args, kinds: tuple[str, ...]) -> int:
    """bridge (sessions) and tactical (battles): each run held to its DOS recording. With both
    compilers, the two runs' entries are also held to each other."""
    scripts = [s for s in find_scripts(args.scripts, kinds) if (RECORDED / recording_of(s)).is_dir()]
    if not scripts:
        raise SetupError("no script with a DOS recording")
    compilers = ["rust", "pe"] if args.compiler == "both" else [args.compiler]
    known = dosshot.read_known()
    masks = dosshot.map_masks()
    exes = build_all(compilers)
    fonts = {c: load_fonts(c) for c in compilers}
    work = [(s, c) for c in compilers for s in scripts]

    def one(item):
        s, c = item
        run = run_script(s, c, exes)
        return run, hold_to_recording(run, recording_of(s), known, fonts[c], masks, s.kind == "battle")

    failed, used, runs = 0, set(), {}
    for run, held in parallel(args.jobs, [lambda i=i: one(i) for i in work]):
        runs[run.script.name, run.compiler] = run
        used |= held.used
        ok = not run.problem and not held.bad
        failed += not ok
        print(f"{'PASS' if ok else 'FAIL'} {run.script.name} [{run.compiler}] {run.seconds:.0f} s: {held.summary}"
              + (f"; {run.problem}" if run.problem else ""), flush=True)
        for line in held.lines:
            print(line)
    if len(compilers) == 2:
        for s in scripts:
            a, b = (runs[s.name, c].reference_entries() for c in compilers)
            same = a == b and bool(a)
            failed += not same
            print(f"{'SAME' if same else 'DIFFERENT'} {s.name}: rust and pe, {len(a)} and {len(b)} entries")
    # A known difference that no run of this command met: the list says more than is true. Only
    # a run of every script of the command can tell, and only the lines of its kind of run count.
    names = {s.name for s in scripts}
    for k in known if not args.scripts else []:
        if k.line not in used and any(fnmatch.fnmatchcase(n, k.run) for n in names):
            print(f"note: known difference not met: {dosshot.KNOWN_FILE.name} line {k.line}: "
                  f"{k.run} {k.shot} {k.kind} {' '.join(k.args)}")
    print(f"{len(work) - failed} passed, {failed} failed" if len(compilers) == 1 else f"{failed} failed")
    return 1 if failed else 0


def recording_of(script: Script) -> str:
    """The folder of tests/recorded that holds the script's DOS recording."""
    for name, (session, _) in BATTLED_SESSIONS.items():
        if script.name == name:
            return session
    return script.name


